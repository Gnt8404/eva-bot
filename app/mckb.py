def lookup(question):
    """Подобрать ответ из базы. Возвращает текст или пустую строку."""
    low = (question or "").lower().replace("ё", "е")
    if len(low) < 3:
        return ""
    best, best_score = "", 0
    for keys, title, text in TOPICS:
        score = 0
        for key in keys:
            if key in low:
                score += 2 if " " in key else 1
        if score > best_score:
            best_score, best = score, "%s\n%s" % (title, text)
    for keys, text in SHORT:
        score = 0
        for key in keys:
            if key in low:
                score += 3 if " " in key else 1
        if score > best_score:
            best_score, best = score, text
    if best_score < 2:
        return ""
    return best


def block(question, limit=1800):
    """Готовый блок для модели: подсказка по теме вопроса."""
    text = lookup(question)
    return text[:limit] if text else ""


def titles():
    return [t for _, t, _ in TOPICS]
