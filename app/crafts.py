def _load_extra_recipes():
    """Крафты плагинов из knowledge/*_crafts.json (например, rift_crafts.json)."""
    folder = os.path.join(_config.ROOT, "knowledge")
    try:
        names = sorted(os.listdir(folder))
    except OSError:
        return 0
    added = 0
    for name in names:
        if not name.lower().endswith("_crafts.json"):
            continue
        path = os.path.join(folder, name)
        try:
            with open(path, "r", encoding="utf-8") as fh:
                data = json.load(fh)
        except Exception as exc:  # noqa: BLE001
            log.warning("крафты %s не прочитались: %s", name, exc)
            continue
        items = data.get("recipes") if isinstance(data, dict) else data
        for item in items or []:
            if not isinstance(item, dict):
                continue
            out = str(item.get("out") or "").strip()
            ingredients = item.get("ingredients") or {}
            if not out or not isinstance(ingredients, dict):
                continue
            clean = {}
            for key, value in ingredients.items():
                try:
                    count = int(value)
                except (TypeError, ValueError):
                    count = 1
                if count > 0:
                    clean[str(key).strip()] = count
            if not clean:
                continue
            station = str(item.get("station") or STATION_TABLE).strip() or STATION_TABLE
            note = str(item.get("note") or "").strip()
            tag = str(item.get("tag") or "плагин").strip()
            try:
                count_out = int(item.get("count") or 1)
            except (TypeError, ValueError):
                count_out = 1
            RECIPES.append(Recipe(out, count_out, None, clean, station, None, note, tag))
            added += 1
    if added:
        log.info("крафты плагинов: добавлено %d", added)
    return added


EXTRA_CRAFTS = _load_extra_recipes()

