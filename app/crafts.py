STATION_TABLE = "Верстак"
STATION_FURNACE = "Печь / Коптильня"


class Recipe:
    __slots__ = ("out", "count", "grid", "key", "station", "smelt", "note", "tag")

    def __init__(self, out, count=1, grid=None, key=None, station=STATION_TABLE,
                 smelt=None, note="", tag=""):
        self.out = out
        self.count = count
        self.grid = grid
        self.key = key or {}
        self.station = station
        self.smelt = smelt           # (время сек, топливо) для плавки
        self.note = note
        self.tag = tag

    def ingredients(self):
        items = {}
        if self.grid:
            for row in self.grid:
                for ch in row:
                    if ch not in (".", " "):
                        name = self.key.get(ch, ch)
                        items[name] = items.get(name, 0) + 1
        elif self.key:
            for name, n in self.key.items():
                items[name] = items.get(name, 0) + n
        return items

    def render(self):
        lines = []
        lines.append("%s x%d" % (self.out, self.count))
        lines.append("Станция: %s" % self.station)
        if self.grid:
            lines.append("Сетка:")
            for row in self.grid:
                lines.append("  " + " ".join("." if c == "." else c for c in row))
            legend = ", ".join("%s = %s" % (k, v) for k, v in self.key.items())
            if legend:
                lines.append("Обозначения: " + legend)
        else:
            lines.append("Ингредиенты: " + ", ".join(
                "%s x%d" % (k, v) for k, v in self.key.items()))
        if self.smelt:
            lines.append("Плавка: %s сек в печи/коптильне/на костре" % self.smelt[0])
        if self.note:
            lines.append("Примечание: %s" % self.note)
        return "\n".join(lines)


RECIPES = []


def shaped(out, grid, key, count=1, station=STATION_TABLE, note="", tag=""):
    RECIPES.append(Recipe(out, count, list(grid), dict(key), station, None, note, tag))


def shapeless(out, key, count=1, station=STATION_TABLE, note="", tag=""):
    RECIPES.append(Recipe(out, count, None, dict(key), station, None, note, tag))


def smelted(out, src, note="", tag="", station=STATION_FURNACE):
    RECIPES.append(Recipe(out, 1, None, {src: 1}, station, (10, "уголь/доски"), note, tag))


