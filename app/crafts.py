def _norm(text):
    text = (text or "").lower().replace("ё", "е")
    text = re.sub(r"[^\w\s\-()]", " ", text)
    return " ".join(text.split())


def _words(query):
    q = _norm(query)
    for en, ru in SYNONYMS.items():
        if en and en in q:
            q = q.replace(en, ru)
    return [w for w in q.split() if len(w) >= 3]


def find(query, limit=4):
    """Что за рецепт у этого предмета."""
    words = _words(query)
    if not words:
        return []
    hits = []
    for rec in RECIPES:
        name = _norm(rec.out)
        score = 0
        for w in words:
            if w in name:
                score += 3 if name.startswith(w) else 2
        if score:
            hits.append((score, rec))
    if not hits:
        return []
    hits.sort(key=lambda pair: (-pair[0], len(pair[1].out)))
    return [rec for _, rec in hits[:limit]]


def what_from(item, limit=8):
    """Что можно сделать из этого предмета."""
    words = _words(item)
    if not words:
        return []
    out = []
    for rec in RECIPES:
        for name in rec.ingredients():
            if any(w in _norm(name) for w in words):
                out.append(rec)
                break
    return out[:limit]


def block(query, limit=14):
    """Текстовый блок с рецептами для подстановки в контекст ИИ."""
    recs = find(query, limit=2)
    if not recs:
        return ""
    parts = []
    for rec in recs:
        parts.append(rec.render())
    return "\n---\n".join(parts)


